#!/usr/bin/env python3
"""Extract the embedded device modules (.asciz strings that are PTX / GCN /
AIR text, or large .byte/.ascii blobs) from main-vs-branch host asm and
compare them. Host-side differences (source line numbers baked into error
paths) are reported separately and are not device code."""
import gzip, re, sys, hashlib, os
D = os.path.dirname(os.path.abspath(__file__))
def blobs(path):
    s = gzip.open(path, 'rt', errors='replace').read()
    out = []
    for m in re.finditer(r'^\s*\.(asciz|ascii)\s+"((?:[^"\\]|\\.)*)"', s, re.M):
        t = m.group(2)
        if len(t) > 2000 and ('.entry' in t or 'amdgcn' in t or '.amdhsa' in t or 'target triple' in t or 'Generated by LLVM' in t):
            out.append(t)
    # also large .byte runs following a device-module label
    return out, s
res = []
for f in sorted(os.listdir(D)):
    if not f.startswith('main-') or not f.endswith('.s.gz'): continue
    tag = f[5:-5]
    bm, sm = blobs(os.path.join(D, f)); bb, sb = blobs(os.path.join(D, 'branch-' + tag + '.s.gz'))
    hm = [hashlib.sha256(x.encode()).hexdigest()[:16] for x in bm]
    hb = [hashlib.sha256(x.encode()).hexdigest()[:16] for x in bb]
    same = hm == hb
    print(f"{tag}: device_modules main={len(hm)} branch={len(hb)} identical={same}")
    if not same:
        ms, bs = set(hm), set(hb)
        print(f"   only-main {len(ms-bs)} only-branch {len(bs-ms)}")
    # host diff lines that are NOT plain immediate changes
    lm, lb = sm.splitlines(), sb.splitlines()
    if len(lm) == len(lb):
        other = [(a, b) for a, b in zip(lm, lb) if a != b and not (re.sub(r'\$\d+', '$N', a) == re.sub(r'\$\d+', '$N', b))]
        other = [(a, b) for a, b in other if not ('.asciz' in a and '.asciz' in b)]
        print(f"   host lines differing beyond integer immediates: {len(other)}")
        for a, b in other[:3]: print('     <', a[:160]); print('     >', b[:160])
    else:
        print(f"   line counts differ: {len(lm)} vs {len(lb)}")
