"""Generate native test fixtures from independent float64 finite differences.

Python/NumPy are test tools only. The generated suite executes all product
operations, graph traversal, and gradient computation in compiled Mojo.
"""
from pathlib import Path
import json
import numpy as np


def softmax(x):
    e = np.exp(x - x.max(axis=1, keepdims=True))
    return e / e.sum(axis=1, keepdims=True)


def log_softmax(x):
    shifted = x - x.max(axis=1, keepdims=True)
    return shifted - np.log(np.exp(shifted).sum(axis=1, keepdims=True))


def main():
    cases = []
    x = np.array([[0.3, -0.8, 1.2], [0.7, 0.2, -0.4]])
    row = np.array([[0.9, 1.3, 0.6]])
    col = np.array([[1.1], [0.8]])

    def case(name, inputs, code, fn):
        cases.append((name, inputs, code, fn))

    for method, fn in [('add', np.add), ('subtract', np.subtract),
                       ('multiply', np.multiply), ('divide', np.divide)]:
        for layout, b in [('row', row), ('column', col), ('scalar', np.array([[1.7]]))]:
            case(f'{method}_{layout}', {'x': x, 'b': b},
                 f'var out = tape.{method}(ex, x, b)',
                 lambda v, fn=fn: fn(v['x'], v['b']))
    unary = [('relu', lambda z: np.maximum(z, 0)),
             ('sigmoid', lambda z: 1 / (1 + np.exp(-z))),
             ('tanh', np.tanh), ('exp', np.exp), ('log', np.log), ('sqrt', np.sqrt)]
    for method, fn in unary:
        a = x + 2 if method in ('log', 'sqrt') else x
        case(method, {'x': a}, f'var out = tape.{method}(ex, x)', lambda v, fn=fn: fn(v['x']))
    case('scale', {'x': x}, 'var out = tape.scale(ex, x, -1.7)', lambda v: v['x'] * -1.7)
    for method, fn in [('sum', np.sum), ('mean', np.mean)]:
        for axis in [-1, 0, 1]:
            case(f'{method}_axis_{axis}', {'x': x}, f'var out = tape.{method}(ex, x, {axis})',
                 lambda v, fn=fn, axis=axis: np.atleast_2d(fn(v['x'], axis=None if axis == -1 else axis, keepdims=True)))
    w = np.array([[0.7, -0.2], [0.1, 0.4], [-0.5, 0.8]])
    case('matmul', {'x': x, 'w': w}, 'var out = tape.matmul(ex, x, w)', lambda v: v['x'] @ v['w'])
    case('transpose', {'x': x}, 'var out = tape.transpose(ex, x)', lambda v: v['x'].T)
    case('reshape', {'x': x}, 'var out = tape.reshape(ex, x, 3, 2)', lambda v: v['x'].reshape(3, 2))
    case('shared_matmul', {'x': x}, 'var xt = tape.transpose(ex, x)\nvar out = tape.matmul(ex, x, xt)', lambda v: v['x'] @ v['x'].T)
    for method, fn in [('softmax', softmax), ('log_softmax', log_softmax)]:
        case(method, {'x': x}, f'var out = tape.{method}(ex, x)', lambda v, fn=fn: fn(v['x']))
    case('mse', {'x': x, 'b': row}, 'var out = tape.mse_loss(ex, x, b)', lambda v: np.array([[np.mean((v['x'] - v['b']) ** 2)]]))
    target = np.array([[0.0, 1.0, 0.0], [0.2, 0.3, 0.5]])
    case('cross_entropy', {'x': x * 70, 'target': target},
         'var out = tape.cross_entropy(ex, x, target)',
         lambda v: np.array([[-np.sum(log_softmax(v['x']) * v['target']) / v['x'].shape[0]]]))
    case('layer_norm', {'x': x, 'w': row, 'b': row * 0.2},
         'var out = layer_norm(tape, ex, x, w, b)',
         lambda v: (v['x'] - v['x'].mean(axis=1, keepdims=True)) / np.sqrt(v['x'].var(axis=1, keepdims=True) + 1e-5) * v['w'] + v['b'])
    case('composite_shared_residual', {'x': x, 'w': np.eye(3) * 0.7 + 0.1, 'b': row * 0.1},
         'var a = tape.matmul(ex, x, w)\nvar b1 = tape.add(ex, a, b)\nvar h = tape.tanh(ex, b1)\nvar z = tape.matmul(ex, h, w)\nvar skip = tape.add(ex, z, x)\nvar out = tape.mse_loss(ex, skip, b)',
         lambda v: np.array([[np.mean((np.tanh(v['x'] @ v['w'] + v['b']) @ v['w'] + v['x'] - v['b']) ** 2)]]))

    lines = ['# SPDX-License-Identifier: Apache-2.0',
             '# Generated by generate_oracles.py; expected gradients are float64 central differences.',
             'from autograd import Tape', 'from autograd.layers import layer_norm, NeuralRules',
             'from sequence.exec_trait import Exec', 'from autograd.checks.support import check_values', '']
    records = []

    def literal(values):
        return '[' + ', '.join(f'Float32({float(v):.12g})' for v in np.asarray(values).flat) + ']'

    for name, inputs, code, fn in cases:
        # Use exactly representable product inputs in the finite-difference oracle.
        inputs = {k: v.astype(np.float32).astype(np.float64) for k, v in inputs.items()}
        out = np.atleast_2d(fn(inputs))
        seed = np.linspace(-0.6, 0.9, out.size).reshape(out.shape).astype(np.float32).astype(np.float64)
        if out.size == 1:
            seed[:] = 1
        expected = {}
        for k, value in inputs.items():
            grad = np.zeros_like(value)
            for index in np.ndindex(value.shape):
                original = value[index]
                step = 1e-5 * max(1.0, abs(original))
                value[index] = original + step
                plus = float(np.sum(fn(inputs) * seed))
                value[index] = original - step
                minus = float(np.sum(fn(inputs) * seed))
                value[index] = original
                grad[index] = (plus - minus) / (2 * step)
            expected[k] = grad
        symbol = name.replace('-1', 'all')
        lines += ['', f'def _{symbol}[E: Exec](mut ex: E, mut tape: Tape) raises:', '    tape.reset()']
        for k, value in inputs.items():
            lines.append(f'    var {k} = tape.tensor(ex, {literal(value)}, {value.shape[0]}, {value.shape[1]}, True)')
        lines += ['    ' + line for line in code.splitlines()]
        lines.append(f'    check_values("{name}/value", tape.values(ex, out), {literal(out)})')
        lines.append(f'    var seed = tape.tensor(ex, {literal(seed)}, {out.shape[0]}, {out.shape[1]})')
        lines.append('    tape.backward_with_rules(ex, out, seed, NeuralRules())')
        for k, grad in expected.items():
            lines.append(f'    check_values("{name}/{k}", tape.gradients(ex, {k}), {literal(grad)})')
        records.append({'case': name, 'input_elements': sum(v.size for v in inputs.values()), 'output_elements': out.size})
    lines += ['', 'def run_gradient_checks[E: Exec](mut ex: E) raises:', '    var tape = Tape()']
    for name, *_ in cases:
        lines.append(f'    _{name.replace("-1", "all")}(ex, tape)')
    lines.append(f'    print("PASS finite-difference cases={len(cases)}")')
    root = Path(__file__).resolve().parent
    (root / 'gradients.mojo').write_text('\n'.join(lines) + '\n')
    (root / 'oracle_manifest.json').write_text(json.dumps({'method': 'NumPy float64 central differences, epsilon=1e-5*max(1,abs(x)); float32-representable inputs', 'numpy': np.__version__, 'cases': records}, indent=2) + '\n')
    print(json.dumps({'cases': len(cases), 'gradient_elements': sum(r['input_elements'] for r in records)}))


if __name__ == '__main__':
    main()
