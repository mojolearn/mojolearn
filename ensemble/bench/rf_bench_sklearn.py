#!/usr/bin/env python3
"""The scikit-learn arm of the random-forest benchmark.

Prints `ARM <name> <ms>` lines that `bench/run_bench.py` alternates against
`ensemble/bench/rf_bench.mojo`.

THE DATASET IS GENERATED BY THE SAME splitmix64 AS THE MOJO ARM, so both fit
the same bits. `--checksum` prints a digest of the generated data; the Mojo
arm prints the same digest, and if the two disagree the timings are
comparing different problems and must be thrown away.

WHAT THIS BASELINE IS. cuML's GPU arm cannot run on Apple silicon, and no
library ships a GPU random forest for this box, so scikit-learn on the same
M4 is the strongest thing that actually runs. It is NOT the same algorithm:
scikit-learn searches exact split thresholds where this port (following
cuML) bins each feature into at most 128 quantiles. That difference favours
us on time, which is exactly why accuracy is printed beside every timing.

scikit-learn gets every core (`n_jobs=-1`). A CPU baseline handicapped to
one thread would not be a baseline.
"""

import argparse
import time

import numpy as np
from sklearn.ensemble import RandomForestClassifier

M = np.uint64(0xFFFFFFFFFFFFFFFF)
REPEATS = 5
N_CLASSES = 4
N_TREES = 20
MAX_DEPTH = 12


def mix(x):
    """splitmix64, transcribed from `rf_bench.mojo::_mix`."""
    h = x + np.uint64(0x9E3779B97F4A7C15)
    h = (h ^ (h >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
    h = (h ^ (h >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
    return h ^ (h >> np.uint64(31))


def make(n_rows, n_cols):
    r = np.arange(n_rows, dtype=np.uint64)[:, None]
    c = np.arange(n_cols, dtype=np.uint64)[None, :]
    with np.errstate(over="ignore"):
        h = mix(r * np.uint64(1000003) + c)
    m = h % np.uint64(10000)
    x = (m.astype(np.float32) / np.float32(10000.0)).astype(np.float32)
    acc = m[:, :3].sum(axis=1, dtype=np.uint64)
    y = ((acc // np.uint64(2500)) % np.uint64(N_CLASSES)).astype(np.int32)
    return np.ascontiguousarray(x), y, m


def digest(m, y):
    """An EXACT integer digest, so summation order cannot muddy it.

    A float sum would not do: numpy sums pairwise and the Mojo arm sums
    sequentially, so the two would differ in the low bits and the check
    would be reporting its own arithmetic rather than the data."""
    return f"{int(m.astype(np.uint64).sum(dtype=np.uint64))}/{int(y.astype(np.int64).sum())}"


def run_arm(name, n_rows, n_cols, want_checksum):
    x, y, m = make(n_rows, n_cols)
    if want_checksum:
        print("SUM", name, digest(m, y))
        return
    for rep in range(REPEATS):
        clf = RandomForestClassifier(
            n_estimators=N_TREES,
            criterion="gini",
            max_depth=MAX_DEPTH,
            min_samples_split=2,
            min_samples_leaf=1,
            max_features=None,   # all features, matching max_features=1.0
            bootstrap=True,
            random_state=20260821,
            n_jobs=-1,
        )
        t0 = time.perf_counter()
        clf.fit(x, y)
        t1 = time.perf_counter()
        print("ARM", name, (t1 - t0) * 1000.0)
        if rep == REPEATS - 1:
            acc = float((clf.predict(x) == y).mean())
            print("ACC", name, acc)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checksum", action="store_true")
    args = ap.parse_args()
    run_arm("rf@100000", 100000, 50, args.checksum)
    run_arm("rf@500000", 500000, 50, args.checksum)


if __name__ == "__main__":
    main()
