"""IDENTICAL-tier CUDA PTX, made contraction-proof in place, and audited.

WHY. The Linux wheel's CUDA sets ship PTX only. The driver JIT compiles it
with fmad on, and ptxas (the JIT included) may fuse a plain `mul.f32` feeding
a plain `add.f32`/`sub.f32` into one FFMA, which rounds once where the source
rounded twice. PTX gives the escape by name: an instruction that carries an
explicit rounding modifier (`mul.rn.f32`) is never contracted. 0.8.19's
IDENTICAL PTX had 920 such contractable pairs (all `mul.f32 x, 0f33800000`
in gbdt `hist2_dither`, exact by construction, so bit-neutral), and rewriting
every plain mul/add/sub (f32, f64) to `.rn` made the fmad=true SASS equal the
fmad=false SASS in all 100 affected modules (ptxas 13.0).

WHY NOT AT THE SOURCE. `mojo build --fp-mode contract=off` does emit `.rn`
for every plain op, but it ALSO stops LLVM from fusing `a*b + c` across
statements, which the default (`contract=fast`) does on NVIDIA and AMD before
any PTX exists (measured 2026-09-25 on a probe kernel: sm_89/sm_90a emit
`fma.rn.f32`, gfx942 `v_fmac_f32`, under the default; `mul.rn`+`add.rn` and
`v_mul`+`v_add` under contract=off). Turning it off changes IDENTICAL bits on
every column, so it is a release-wide decision, not this pass.

THE REWRITE is length-preserving, so it edits the PTX string inside the
shared object without relinking. LLVM's NVPTX printer spells these lines

    \\tmul.f32 \\t%r4, %r2, %r3;

and the rewrite spends exactly the three whitespace bytes it adds:

    mul.rn.f32 %r4,%r2, %r3;

(leading tab dropped, " \\t" to " ", the first ", " to ","). A line in any
other shape is left alone and the audit then refuses it by name.

THE AUDIT refuses any IDENTICAL-tier CUDA PTX that still contains a mul, add,
sub, fma or mad on a floating type with no rounding modifier, and any
IDENTICAL kernel that carries an instruction the PTX ISA documents as
approximate (APPROX: `sqrt.approx`, `rcp.approx`, `div.full`, `ex2.approx`,
...), outside APPROX_ALLOW. Mojo's stdlib lowers Float32 sqrt/log2/exp2/
sin/cos/tanh to those on NVPTX; IDENTICAL code reaches the exact routines of
checks/numerics.mojo instead. 2026-11-17 (lane fb13): until then approximate
instructions were only counted, and one product kernel (IterativeImputer's
|corr|) shipped `sqrt.approx` for weeks, found by hand. The audit runs where
the build runs `audit` (packaging/linux/build_sets.sh, before the cubin pass)
and in the wheel audit (packaging/portable_math/wheel.py).
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys

#: A PTX module in a binary: `.version X.Y` up to the NUL that ends the string.
_VERSION = re.compile(rb"\.version \d+\.\d+")
_LLVM_HEADER = b"//\n// Generated by LLVM NVPTX Back-End\n//\n\n"
_TARGET = re.compile(rb"^\s*\.target\s+sm_", re.M)
#: A float mul/add/sub/fma/mad with NO rounding modifier (.rn/.rz/.rm/.rp).
#: `mul.rn.ftz.f32` does not match: the modifier group admits only .ftz/.sat.
PLAIN = re.compile(
    rb"^[ \t]*(?:@!?%\w+[ \t]+)?(add|sub|mul|fma|mad)((?:\.(?:ftz|sat))*)"
    rb"\.(f16x2|f16|bf16x2|bf16|f32|f64)(?=[ \t])", re.M)
#: The exact line shape the rewrite knows how to lengthen for free.
_REWRITE = re.compile(rb"(?<=\n)\t(add|sub|mul)\.(f32|f64) \t([^,\n]+), ")
#: Instructions the PTX ISA documents as NOT correctly rounded (PTX ISA 8.5, "Floating-Point Instructions"):
#: sqrt/rsqrt/rcp/div `.approx` (fast approximations, max error stated in ulp), `div.full` (2 ulp, full-range
#: approximation), ex2/lg2/sin/cos/tanh `.approx` (the only forms those ops have). Their results are NVIDIA's
#: own and differ from every other column, so an IDENTICAL kernel that carries one is refused (APPROX_ALLOW).
#: The correctly rounded forms (`sqrt.rn`, `rcp.rn`, `div.rn`, `fma.rn`) and integer `div` are not matched.
APPROX = re.compile(rb"\b((?:sqrt|rsqrt|rcp|ex2|lg2|sin|cos|tanh|div)\.(?:approx|full)[.a-z0-9]*)")
#: The only IDENTICAL-set kernels allowed to carry an approximate instruction: (name pattern, reason). Nothing
#: else is: fix the source through checks/numerics.mojo's exact routines (identical_sqrt, identical_exp, ...).
#: Kernel names are `<module path cut to 30 characters>6A..._<hash>`, so each prefix names one source file.
_SABOTAGE = ("verify sabotage kernel, raw stdlib math broken ON PURPOSE so the native check (and verify) can fail;"
             " reached only at a non-NONE sabotage arm, never by an estimator: {}")
APPROX_ALLOW = (
    (re.compile(r"^hierarchy_checks_sabotage_tile"), _SABOTAGE.format("hierarchy/checks/sabotage_tile.mojo")),
    (re.compile(r"^cholesky_checks_chol_sabotage"), _SABOTAGE.format("cholesky/checks/chol_sabotage.mojo")),
    (re.compile(r"^gaussian_process_checks_gp_sab"), _SABOTAGE.format("gaussian_process/checks/gp_sabotage.mojo")),
    (re.compile(r"^kernel_methods_checks_km_sabot"), _SABOTAGE.format("kernel_methods/checks/km_sabotage.mojo")),
)
#: A PTX function header (`.entry` kernel or `.func` device function, optional return parameter list).
_FUNC = re.compile(rb"^[ \t]*(?:\.(?:visible|weak|extern)[ \t]+)*\.(?:entry|func)[ \t]+(?:\([^)]*\)[ \t]*)?([\w$.]+)",
                   re.M)


def approx_sites(text):
    """[(function, op)] for every approximate instruction in one PTX module, attributed to the `.entry` or `.func`
    whose body holds it (Mojo kernels carry no line info; the name's module-path prefix locates the source)."""
    heads = [(m.start(), m.group(1).decode("ascii", "replace")) for m in _FUNC.finditer(text)]
    out, k = [], -1
    for m in APPROX.finditer(text):
        while k + 1 < len(heads) and heads[k + 1][0] < m.start():
            k += 1
        out.append((heads[k][1] if k >= 0 else "<module scope>", m.group(1).decode()))
    return out


#: The vendor-math row (checks/mode_policy.mojo ROW_VENDOR_MATH, -D MOJOLEARN_MODE_FAST_VENDOR_MATH) puts the
#: vendor's math forms in every kernel ON PURPOSE: it is a fast-rows measurement build (MOJOLEARN_MODE_FAST_ROWS;
#: mode_policy's comptime assert refuses the row in any build that promises identical bits), never shipped, built
#: in the identical set's directory only to time the cost of exact math. Its approximate instructions are counted
#: and allowed; a build without the row is audited exactly as before. Lane fx-small, 2026-11-21: arm
#: fast-vendor-math failed assemble sm_89 twice (run 44876740092, full46-build exit 1) on this refusal.
_VENDOR_MATH_ROW = "MOJOLEARN_MODE_FAST_VENDOR_MATH"
_VENDOR_MATH_WHY = "fast-rows measurement build with the vendor-math row (" + _VENDOR_MATH_ROW + "): not shipped"


def vendor_math_build(defines=None):
    """True when the build's defines (MOJOLEARN_BUILD_DEFINES, bindings/build_defines.sh: comma-separated NAME or
    NAME=VALUE) carry both the vendor-math row and MOJOLEARN_MODE_FAST_ROWS."""
    raw = os.environ.get("MOJOLEARN_BUILD_DEFINES", "") if defines is None else defines
    names = {d.split("=", 1)[0] for d in raw.split(",") if d}
    return _VENDOR_MATH_ROW in names and "MOJOLEARN_MODE_FAST_ROWS" in names


def approx_allowed(function, vendor_math=False):
    """The APPROX_ALLOW reason for `function`, or None (every function in a vendor-math build)."""
    if vendor_math:
        return _VENDOR_MATH_WHY
    return next((why for rx, why in APPROX_ALLOW if rx.search(function)), None)


def is_identical_cuda(relative):
    """`mojolearn/cuda/<arch>/identical/<name>.so`: the tier this pass owns, and
    the framework adapters' native library `mojolearn/cuda/<arch>/_adapters/
    libmojolearn_adapter.so`, compiled with the IDENTICAL tier's flags
    (packaging/adapters/build.sh) and held to the same PTX and machine-code rules."""
    parts = Path(relative).parts
    return (len(parts) == 5 and parts[0] == "mojolearn" and parts[1] in ("cuda", "cuda_native")
            and (parts[3] == "identical" and parts[4].endswith(".so")
                 or parts[3] == "_adapters" and parts[4] == "libmojolearn_adapter.so"))


def modules(data):
    """(start, end) of every PTX module string in `data`."""
    spans, last = [], -1
    for m in _VERSION.finditer(data):
        start = data.rfind(b"\0", 0, m.start()) + 1
        # A preceding binary constant need not end in NUL. In the split
        # sm_89 cluster library this included 183 unrelated bytes before the
        # compiler's PTX string and crashed ptxas. The emitted LLVM header
        # identifies the actual string start; the library's lea points there.
        # This locates the existing module without changing its instructions.
        header = m.start() - len(_LLVM_HEADER)
        if header >= start and data[header:m.start()] == _LLVM_HEADER:
            start = header
        if start <= last:
            continue
        end = data.find(b"\0", m.start())
        end = len(data) if end < 0 else end
        if _TARGET.search(data, start, min(end, start + 4096)):
            spans.append((start, end))
            last = end
    return spans


def rewrite_ptx(text):
    """PTX text -> (same-length text with plain f32/f64 mul/add/sub made .rn, count)."""
    out, n = _REWRITE.subn(rb"\1.rn.\2 \3,", text)
    if len(out) != len(text):
        raise AssertionError("the .rn rewrite changed the PTX length")
    return out, n


def plain_ops(text):
    """Every float mul/add/sub/fma/mad line with no rounding modifier."""
    lines = []
    for m in PLAIN.finditer(text):
        end = text.find(b"\n", m.start())
        lines.append(text[m.start():end if end >= 0 else len(text)].strip().decode("ascii", "replace"))
    return lines


def patch_bytes(data):
    """A binary's bytes -> (bytes with every PTX module rewritten in place, modules, rewrites)."""
    buf = bytearray(data)
    spans = modules(data)
    total = 0
    for start, end in spans:
        new, n = rewrite_ptx(bytes(buf[start:end]))
        buf[start:end] = new
        total += n
    return bytes(buf), len(spans), total


def audit_bytes(data):
    """{modules, plain: [first offending lines], plain_count, approx: {op: count},
    approx_refused: ["function: op"] (not in APPROX_ALLOW), approx_allowed: {function: reason}}."""
    report = {"modules": 0, "plain_count": 0, "plain": [], "approx": {}, "approx_refused": [], "approx_allowed": {}}
    vendor_math = vendor_math_build()  # once per binary, not per site
    for start, end in modules(data):
        text = data[start:end]
        report["modules"] += 1
        bad = plain_ops(text)
        report["plain_count"] += len(bad)
        report["plain"].extend(bad[:max(0, 5 - len(report["plain"]))])
        for function, op in approx_sites(text):
            report["approx"][op] = report["approx"].get(op, 0) + 1
            why = approx_allowed(function, vendor_math)
            if why:
                report["approx_allowed"][function] = why
            elif f"{function}: {op}" not in report["approx_refused"]:
                report["approx_refused"].append(f"{function}: {op}")
    return report


def patch_file(path):
    data = Path(path).read_bytes()
    new, n_mod, n_rw = patch_bytes(data)
    if new != data:
        Path(path).write_bytes(new)
    return {"file": str(path), "modules": n_mod, "rewritten": n_rw}


def patch_tree(root):
    """Rewrite every IDENTICAL-tier CUDA binary under an unpacked wheel root."""
    root = Path(root)
    return [dict(patch_file(p), file=p.relative_to(root).as_posix())
            for p in sorted(root.rglob("*.so")) if is_identical_cuda(p.relative_to(root).as_posix())]


def audit_tree(root):
    """(errors, per-binary reports) for every IDENTICAL-tier CUDA binary under `root`."""
    root = Path(root)
    errors, rows = [], []
    for p in sorted(root.rglob("*.so")):
        rel = p.relative_to(root).as_posix()
        if not is_identical_cuda(rel):
            continue
        r = audit_bytes(p.read_bytes())
        rows.append({"file": rel, "ptx_modules": r["modules"], "plain_float_ops": r["plain_count"],
                     "approx": r["approx"], "approx_refused": r["approx_refused"]})
        if r["plain_count"]:
            errors.append(f"{rel}: {r['plain_count']} float mul/add/sub/fma without a rounding modifier"
                          f" in IDENTICAL PTX (the driver JIT may contract them), first: {r['plain']}")
        if r["approx_refused"]:
            errors.append(f"{rel}: {len(r['approx_refused'])} IDENTICAL kernel(s) carry an approximate instruction"
                          f" (NVIDIA-only bits; route through checks/numerics.mojo): {r['approx_refused']}")
    return errors, rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mode", choices=("patch", "audit"))
    ap.add_argument("paths", nargs="+", type=Path, help=".so files (patched/audited whatever their path)")
    a = ap.parse_args()
    rc = 0
    for p in a.paths:
        if a.mode == "patch":
            print(json.dumps(patch_file(p)))
        else:
            r = audit_bytes(p.read_bytes())
            print(json.dumps({"file": str(p), "ptx_modules": r["modules"], "plain_float_ops": r["plain_count"],
                              "first": r["plain"], "approx": r["approx"], "approx_refused": r["approx_refused"],
                              "approx_allowed": r["approx_allowed"]}))
            rc |= bool(r["plain_count"]) or bool(r["approx_refused"])
    return rc


if __name__ == "__main__":
    sys.exit(main())
