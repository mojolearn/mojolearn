#!/usr/bin/env python3
"""Admit complete same-release Apple/NVIDIA/AMD tiny bitwise captures."""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT/'python/mojolearn'/f'{name}.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for vendor in ('metal', 'cuda', 'hip'):
        parser.add_argument('--' + vendor, required=True, type=Path)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    data = dict(witnesses={v: json.loads(getattr(args, v).read_text()) for v in ('metal', 'cuda', 'hip')})
    errors = load('_verify_light_command').reference_errors(data, load('_verify_light'))
    if errors:
        parser.error('; '.join(errors))
    # JSON strings avoid a large literal AST; all raw output bytes and native
    # artifact hashes stay in the package. Paths describe the captured hosts.
    payload = json.dumps(data, sort_keys=True, separators=(',', ':'))
    args.out.write_text('"""Generated by tools/light_verifier_reference.py; eight fixtures only."""\n'
                        'import json as _json\nDATA = _json.loads(' + repr(payload) + ')\n')
    print('Admitted 8 cases, 118 outputs, three GPU vendors, release ' + data['witnesses']['metal']['version'])


if __name__ == '__main__':
    main()
