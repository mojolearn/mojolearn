#!/usr/bin/env python3
"""Generate typed provider tables from retained packed ABI entry definitions.

The existing CPU/GPU wrappers remain the A/B boundary oracle. This generator
copies their scalar admission and calls to unchanged numerical owners; it never
regenerates numerical drivers or changes compile-time routes. Some retained
wrappers extend x_neighbors/gen.py, so consume their current source definitions
rather than silently replacing those extensions with an older OPS snapshot.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = '# SPDX-License-Identifier: Apache-2.0\n# Generated by tools/gen_x_neighbors_provider.py; numerical owners unchanged.\n'
# Append-only: published packed/mode/auxiliary operation IDs remain stable.
EXTRA = [('ocsvm_alpha_init',(2,1,1)),('unit_ff',(3,1,0)),('ocsvm_resident',(5,5,3)),('capabilities',(0,0,0)),('pcs_draw',(2,3,0))]
PATTERN = re.compile(r'^def (\w+)_binding\(a_: PythonObject, i_: PythonObject, f_: PythonObject\) raises -> PythonObject:\n(.*?)(?=^def |\Z)', re.M | re.S)


def unpack(source):
    rows = []
    for match in PATTERN.finditer(source):
        name, body = match.groups()
        counts = []
        for helper, argument in (('_a','a_'),('_n','i_'),('_f','f_')):
            slots = [int(n) for n in re.findall(rf'{helper}\({argument}, (\d+)\)', body)]
            assert sorted(slots) == list(range(len(slots))), (name, helper, slots)
            counts.append(len(slots))
        # These packed wrappers release the GIL around exactly their native
        # owner call. The shared provider owns that GIL transition instead.
        lines, released = [], False
        for line in body.splitlines():
            if line == '    with GILReleased(Python()):':
                released = True
                continue
            if released and line.strip() and not line.startswith('        '):
                released = False
            if released and line.startswith('    '):
                line = line[4:]
            lines.append(line)
        body = '\n'.join(lines).replace('return PythonObject(None)', 'return 0').rstrip() + '\n'
        assert 'PythonObject' not in body and 'GILReleased' not in body and 'py=' not in body, name
        rows.append((name, tuple(counts), body))
    return rows


def native_imports(source):
    lines = source.splitlines()
    output = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith(('from x_neighbors.', 'from checks.numerics ', 'from experiments.')) and not line.startswith(('from x_neighbors.native_descriptor_', 'from x_neighbors.descriptor_schema ')):
            output.append(line)
            if '(' in line and ')' not in line:
                i += 1
                while i < len(lines):
                    output.append(lines[i])
                    if ')' in lines[i]:
                        break
                    i += 1
        i += 1
    return '\n'.join(output) + '\n'


def table(source, rows, target):
    out = HEADER + '''from std.ffi import _Global
from core.native_descriptor_abi import NativeDescriptorCall, NativeDescriptorError
from core.native_descriptor_call import native_descriptor_words, native_descriptor_report
from x_neighbors.descriptor_schema import XN_ABI_NAME, xn_schema, xn_min_ints
''' + f'from x_neighbors.native_descriptor_aux_{target} import xn_aux_execute\n' + native_imports(source) + '''

def _a(v: List[Int], k: Int) raises -> Int:
    var x = v[k]
    if x == 0:
        raise Error("x_neighbors: null buffer address")
    return x


def _n(v: List[Int], k: Int) raises -> Int:
    var x = v[k]
    if x < 0:
        raise Error("x_neighbors: a negative size was passed")
    return x


def _f(v: List[Float64], k: Int) raises -> Float32:
    return Float32(v[k])
'''
    for name, _, body in rows:
        out += f'\n\ndef xn_native_{name}(a_: List[Int], i_: List[Int], f_: List[Float64]) raises -> Int:\n' + body
    out += '\n\ndef xn_operation(op: Int, a: List[Int], p: List[Int], f: List[Float64]) raises -> Int:\n'
    for index, (name, _, _) in enumerate(rows):
        out += f'    if op == {index}:\n'
        if name == 'softmax64':
            out += '        comptime if not NC_PROBA64:\n            raise Error("AttributeError: xn_softmax64 is not exported by this binding")\n'
        out += f'        return xn_native_{name}(a, p, f)\n'
    out += f'    if op == {len(rows)}:\n        return Int(GLOBAL_NUMERIC_MODE)\n'
    for extra_index, (name, _) in enumerate(EXTRA):
        out += f'    if op == {len(rows)+1+extra_index}:\n        return xn_aux_execute({extra_index}, a, p, f)\n'
    out += '''    raise Error("x_neighbors native ABI: unknown operation")


def xn_native_v1(op: Int, aa: Int, na: Int, pp: Int, np: Int, ff: Int, nf: Int,
                  result: Int, context: Int, sink: NativeDescriptorError) abi("C") -> Int:
    try:
        var shape = xn_schema(op)
        if na != shape[0] or np < xn_min_ints(op) or np > shape[1] or nf != shape[2]:
            raise Error("x_neighbors native ABI: descriptor span differs from the named operation")
        if result == 0 or (nf > 0 and ff == 0):
            raise Error("x_neighbors native ABI: null result or scalar span")
        var a = native_descriptor_words(aa, na)
        var p = native_descriptor_words(pp, np)
        var f = List[Float64]()
        var fp = MutPointer[Float64, MutUntrackedOrigin](unsafe_from_address=ff)
        for i in range(nf):  # small-loop(the fixed scalar count of the named operation)
            f.append(fp[i])
        MutPointer[Int, MutUntrackedOrigin](unsafe_from_address=result)[0] = xn_operation(op, a, p, f)
        return 0
    except problem:
        native_descriptor_report(problem, context, sink)
        return 1


struct XNeighborsNativeAPI(Defaultable, Movable):
    var name: String
    var entries: List[NativeDescriptorCall]

    def __init__(out self):
        self.name = String(XN_ABI_NAME)
        self.entries = List[NativeDescriptorCall]()
        self.entries.append(xn_native_v1)

'''
    out += f'comptime XN_NATIVE_API = _Global[StorageType=XNeighborsNativeAPI,\n    name="MojoXNeighborsNative{target.title()}APIv1", init_fn=XNeighborsNativeAPI.__init__]\n'
    return out


def schema(rows):
    out = HEADER + f'comptime XN_ABI_NAME = "mojolearn.x_neighbors.native.v1"\ncomptime XN_OPERATION_COUNT = {len(rows)+1+len(EXTRA)}\ncomptime XN_MODE_OPERATION = {len(rows)}\n'
    out += '\n\ndef xn_operation_id(name: String) raises -> Int:\n'
    for index, (name, _, _) in enumerate(rows):
        out += f'    if name == "{name}":\n        return {index}\n'
    for index, (name, _) in enumerate(EXTRA):
        out += f'    if name == "{name}":\n        return {len(rows)+1+index}\n'
    out += '    raise Error("x_neighbors native ABI: unknown operation " + name)\n'
    out += '\n\ndef xn_schema(op: Int) raises -> Tuple[Int, Int, Int]:\n'
    for index, (_, counts, _) in enumerate(rows):
        out += f'    if op == {index}:\n        return ({counts[0]}, {counts[1]}, {counts[2]})\n'
    out += f'    if op == {len(rows)}:\n        return (0, 0, 0)\n'
    for index, (name, counts) in enumerate(EXTRA):
        out += f'    if op == {len(rows)+1+index}:\n        return ({counts[0]}, {counts[1]}, {counts[2]})\n'
    out += '    raise Error("x_neighbors native ABI: unknown operation")\n'
    optional = next(index for index, (name, _, _) in enumerate(rows) if name == 'nan_cells')
    out += f'\n\ndef xn_min_ints(op: Int) raises -> Int:\n    # nan_cells has an optional third flag; host ignores it as before.\n    return 2 if op == {optional} else xn_schema(op)[1]\n'
    return out


def generated(root):
    device = (root / 'bindings/_mojolearn_x_neighbors.mojo').read_text()
    host = (root / 'bindings/_mojolearn_x_neighbors_host.mojo').read_text()
    rows, host_rows = unpack(device), unpack(host)
    assert [name for name, _, _ in rows] == [name for name, _, _ in host_rows]
    for device_row, host_row in zip(rows, host_rows):
        if device_row[1] != host_row[1]:
            # Existing optional GPU nan_cells flag; host has no flag slot.
            assert device_row[:2] == ('nan_cells', (4, 3, 0)) and host_row[:2] == ('nan_cells', (4, 2, 0))
    assert rows
    return {'x_neighbors/descriptor_schema.mojo':schema(rows),
            'x_neighbors/native_descriptor_device.mojo':table(device,rows,'device'),
            'x_neighbors/native_descriptor_host.mojo':table(host,host_rows,'host')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = generated(ROOT)
    for relative, value in outputs.items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit('generated native provider differs: ' + relative)
        else:
            path.write_text(value)
    print(f'x_neighbors provider: {len(unpack((ROOT / "bindings/_mojolearn_x_neighbors.mojo").read_text()))} packed operations, CPU/GPU schema matched')

if __name__ == '__main__':
    main()
