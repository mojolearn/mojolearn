def _fake_git(tmp_path, listing):
    """A `git` on PATH that logs each argv line and answers `grep` with `listing`."""
    bindir = tmp_path / "bin"
    bindir.mkdir()
    log = tmp_path / "git.log"
    script = bindir / "git"
    script.write_text("#!/bin/sh\n"
                      f'printf "%s\\n" "$*" >> "{log}"\n'
                      'case " $* " in *" grep "*) cat "' + str(tmp_path / "listing") + '";; esac\n')
    script.chmod(script.stat().st_mode | stat.S_IEXEC)
    (tmp_path / "listing").write_text("".join(f"{p}\n" for p in listing))
    return bindir, log


