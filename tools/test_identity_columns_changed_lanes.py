EXCLUDED = ("experiments", "bench/results", "docs")


def _fake_git(tmp_path, listing):
    """A `git` on PATH that logs each argv line and answers `grep` with `listing`."""
    bindir = tmp_path / "bin"
    bindir.mkdir()
    log = tmp_path / "git.log"
    script = bindir / "git"
    script.write_text("#!/bin/sh\n"
                      f'printf "%s\\n" "$*" >> "{log}"\n'
                      'case " $* " in *" grep "*) cat "' + str(tmp_path / "listing") + '";; esac\n')
    script.chmod(script.stat().st_mode | stat.S_IEXEC)
    (tmp_path / "listing").write_text("".join(f"{p}\n" for p in listing))
    return bindir, log


@pytest.fixture
def fake_tree(tmp_path, monkeypatch):
    tree = tmp_path / "tree"
    (tree / "fam").mkdir(parents=True)
    (tree / "fam" / "out_a.mojo").write_text("# GENERATED by gen/a.py; do not edit\nfn f(): pass\n")
    (tree / "fam" / "out_b.mojo").write_text("# GENERATED by gen/b.py\nfn g(): pass\n")
    # prose that mentions a marker inside a string is not an output
    (tree / "fam" / "note.py").write_text('X = "GENERATED by gen/c.py"\n')
    bindir, log = _fake_git(tmp_path, ["fam/out_a.mojo", "fam/out_b.mojo", "fam/note.py"])
    monkeypatch.setenv("PATH", f"{bindir}{os.pathsep}{os.environ['PATH']}")
    monkeypatch.setattr(lane_select, "ROOT", str(tree))
    lane_select.reset_caches()
    yield log
    lane_select.reset_caches()


def _git_calls(log):
    return log.read_text().splitlines() if log.exists() else []


def test_one_bounded_grep_for_many_generator_paths(fake_tree):
    rev = {"fam/out_a.mojo": {"lane_a"}, "fam/out_b.mojo": {"lane_b"}}
    paths = [f"experiments/six_lane_integration/measurements/m{i}.py" for i in range(500)]
    for path in paths:
        assert lane_select.generator_lanes(path, rev) is None
    assert lane_select.generator_lanes("gen/a.py", rev) == ({"lane_a"}, ["fam/out_a.mojo"])
    assert lane_select.generator_lanes("gen/b.py", rev) == ({"lane_b"}, ["fam/out_b.mojo"])
    assert lane_select.generator_lanes("gen/c.py", rev) is None
    calls = _git_calls(fake_tree)
    greps = [c for c in calls if " grep " in f" {c} "]
    assert len(greps) == 1, calls
    assert len(calls) == 1, calls
    grep = greps[0]
    for d in EXCLUDED:
        assert f":(exclude){d}" in grep
    # nothing but the whole tree minus the exclusions is named as a pathspec
    spec = grep.split(" -- ", 1)[1].split()
    assert spec == ["."] + [f":(exclude){d}" for d in EXCLUDED]


def test_select_stops_once_the_asked_lanes_are_decided():
    sources = {"lane_a": ["fam/a.mojo"], "lane_b": ["fam/b.mojo"]}
    sel = lane_select.select(["two paths", "fam/a.mojo"], ref=None, sources=sources,
                             stop_when={"lane_a", "lane_b"})
    assert sel["stopped_early"] is True
    assert sel["unattributed"] == ["two paths"]
    assert "fam/a.mojo" not in sel["reasons"]


def test_changed_lanes_diffs_each_commit_once_with_progress(tmp_path, monkeypatch, capsys):
    lanes = [f"lane{i:03d}" for i in range(170)]
    calls = {"changed_paths": 0, "select": []}
    table = tmp_path / "table.json"
    table.write_text(json.dumps({"cells": {}, "records": []}))
    monkeypatch.setattr(ic, "harness", lambda: types.SimpleNamespace(LANES=lanes))
    monkeypatch.setattr(ic, "profile_lanes", lambda h, scope: list(lanes))
    monkeypatch.setattr(ic, "vref", lambda: types.SimpleNamespace(stale_reference_lanes=lambda t, h: ["lane000"]))
    monkeypatch.setattr(lane_select, "lane_sources", lambda: ({l: [] for l in lanes}, {}))

    def changed_paths(ref):
        calls["changed_paths"] += 1
        return ["x.py"]

    def select(paths, ref=None, sources=None, backend=None, stop_when=None):
        calls["select"].append(set(stop_when))
        return {"lanes": lanes[:100], "unattributed": [], "stopped_early": False}

    monkeypatch.setattr(lane_select, "changed_paths", changed_paths)
    monkeypatch.setattr(lane_select, "select", select)
    args = types.SimpleNamespace(table=str(table), since="abc123", scope="all", no_release_floor=True,
                                 backend="", floor_desc="")
    assert ic.cmd_changed_lanes(args) == 0
    out, err = capsys.readouterr()
    assert calls["changed_paths"] == 1
    assert calls["select"] == [set(lanes[1:])]          # the stale lane is decided without a diff
    assert out.strip().split(",") == lanes[:100]       # same answer: stale lane000 plus the selection
    progress = [l for l in err.splitlines() if l.startswith("# changed-lanes:")]
    assert len(progress) == 3                          # at 50, 100, 150
