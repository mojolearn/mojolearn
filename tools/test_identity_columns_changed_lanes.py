"""`identity_columns.py changed-lanes` STAYS BOUNDED ON A FULL CHECKOUT.

Closed 2026-10-24. lane_select.generator_lanes ran one whole-repository
`git grep -l -F "GENERATED by <path>"` per changed path no lane's source set
holds. On a 20-core droplet with the full repository (experiments/ and
bench/results/ included) `record_identity_column.sh ONLY_CHANGED=table` spent
86 minutes in those greps before printing "CHANGED-LANES 570 of 570".

Now the generated-marker files come from ONE grep per process that never
searches experiments/, bench/results/ or docs/, select() stops once every lane
a commit decides is already selected (or a path is unattributed), and the
command reports progress every 50 lanes. A fake `git` counts the invocations.
"""
