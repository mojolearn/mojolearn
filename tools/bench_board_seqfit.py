"""THE SEQUENCE MODEL FIT LANES of tools/bench_board_neural.py (lane nn-surface, 2026-11-23): models a user
composes from mojolearn.Sequential's public layers, raced against the SAME model composed from PyTorch's own
library modules (torch.nn; mamba_ssm's own scan kernels for the Mamba scans), the same hyperparameters on both
arms, quality beside every time. Nothing here runs a race: bench_board_neural.py imports these tables (standard
library only at import) and its worker builds the arms (OursFit / TorchSeqFitArm).

THE LANES (every value below is explicit and the same on every arm; `T` the steps, `F` the features of a step)
    seq-cnn1d-fit          1D-CNN: conv1d(32, 7, pad 3) relu max_pool1d(2) conv1d(64, 5, pad 2) relu
                           adaptive_avg_pool1d(1) flatten linear(1), on (F, T) samples
    seq-resnet1d-fit       ResNet-1D (Wang et al. 2017, two blocks): conv(32, 7)-bn-relu stem; block 32 channels
                           (conv5-bn-relu-conv3-bn, identity shortcut); block 64 channels (the same, 1x1 conv-bn
                           shortcut); relu after each block; global average pool, linear(1). Convs without bias.
    seq-inceptiontime-fit  InceptionTime (Ismail Fawaz et al. 2020), two inception modules of four branches
                           (bottleneck conv1(8) then conv9 / conv5 / conv3 with 16 outputs; max_pool3 then
                           conv1(16)), joined on the channels, batch norm, relu; global average pool, linear(1).
                           Each conv branch has its own bottleneck (the composition Sequential.parallel takes).
    seq-gru-lengths-fit    GRU(64) over variable-length sequences (lengths T/4 .. T, padded with noise), the
                           final valid state into linear(1). torch: pack_padded_sequence + nn.GRU, h_n.
    seq-lstm-lengths-fit   the same with LSTM(64).
    seq-transformer-fit    a Transformer encoder model, pre-norm: linear(64); x + MHA(LN(x)) (4 heads, no
                           projection bias, no mask, no position encoding); x + FF(LN(x)) (linear 128, exact
                           GELU, linear 64); LN; mean over the steps; linear(1). torch: nn.Linear, nn.LayerNorm,
                           nn.MultiheadAttention(bias=False, batch_first=True), nn.GELU.
    seq-mamba1-fit         a composed Mamba-1 core: linear(96) to [u | delta | B | C] (dim 32, d_state 16),
                           softplus, the selective scan (A = -exp(A_log), A_log[:, n] = log(n + 1), D = 1),
                           mean over the steps, linear(1). torch: nn.Linear, F.softplus and mamba_ssm's
                           selective_scan_fn (delta_softplus=False), the library's selective-scan kernel.
    seq-mamba2-fit         a composed Mamba-2 core: linear(321) to [x | B | C | dt] (one head of 64 channels,
                           128 states), softplus, the SSD scan (chunk 256, A_log = log(1), D = 1), mean over the
                           steps, linear(1). torch: nn.Linear, F.softplus and mamba_ssm's
                           mamba_chunk_scan_combined (chunk_size=256, no dt bias, no dt softplus).
    seq-mamba3-fit         a composed Mamba-3 core: linear(102) to [v | k | q | dt | A | trap] (2 heads of 16
                           channels, 16 states), the trapezoid scan, mean over the steps, linear(1). OURS ALONE:
                           mamba_ssm's Mamba-3 kernel (mamba3_siso_combined) fuses the scan with Mamba-3's own
                           projections, norms and biases, a different model, and a torch scan written by this
                           harness is not an opponent (Race fairness); NOT_PLANNED says so.

THE DATA ("synthetic-seq", "synthetic-seq-lengths"): generated by the conductor (seq_arrays), no download.
X is default_rng(SEED) standard normal (n, T, F) float32. The label is 1 where the strongest response of a fixed
5-step motif filter W (5, F) over the valid steps, max_t sum_{k, f} X[t + k, f] W[k, f] / sqrt(5 F), exceeds the
training rows' median: a temporal pattern a linear model on the flattened rows does not find. The lengths lanes
draw each sequence's length from T/4 .. T; its steps past the length are noise the label never reads. Summed
term by term in one fixed order (no BLAS): the same bytes on every box. The conv lanes read (n, F, T), the
transposed copy made before every clock.

TRAINING (every arm): BCE with logits on one logit, Adam (bench_board_neural.FIT_ADAM: lr, betas, eps, no weight
decay, no amsgrad), SEQ_EPOCHS epochs of shuffled minibatches of SEQ_BATCH, a fresh seeded initialization per
round; the held-out probabilities after the clock. Different initial draws between libraries are a different
random start, not a different setting.
"""

