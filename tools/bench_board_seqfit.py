def seq_arrays(lane, shape, rec, seed):
    """The lane's data (see the module docstring). Bench-side preparation before every clock; no arm computes
    it. Returns X_train, y_train, X_test, y_test (and L_train, L_test on the lengths lanes)."""
    import numpy as np
    r = LANES[lane]
    d = SEQ_SHAPES[shape]
    n, T, F = d["train"] + d["test"], d["length"], d["features"]
    rng = np.random.default_rng(seed)
    X = rng.standard_normal((n, T, F), dtype=np.float32)
    W = rng.standard_normal((MOTIF, F))
    if r["lengths"]:
        L = rng.integers(max(MOTIF, T // 4), T + 1, size=n).astype(np.int64)
    else:
        L = np.full(n, T, dtype=np.int64)
    resp = np.zeros((n, T - MOTIF + 1), dtype=np.float64)
    for k in range(MOTIF):              # one fixed order, elementwise: the same bits on every box
        for f in range(F):
            resp += X[:, k:T - MOTIF + 1 + k, f].astype(np.float64) * W[k, f]
    resp /= np.sqrt(np.float64(MOTIF * F))
    valid = np.arange(T - MOTIF + 1)[None, :] <= (L[:, None] - MOTIF)
    score = np.where(valid, resp, -np.inf).max(axis=1)
    ntr = d["train"]
    threshold = float(np.median(score[:ntr]))
    y = (score > threshold).astype(np.float32)
    if r["layout"] == "channels":
        X = np.ascontiguousarray(X.transpose(0, 2, 1))
    out = {"X_train": np.ascontiguousarray(X[:ntr]), "y_train": y[:ntr].copy(),
           "X_test": np.ascontiguousarray(X[ntr:]), "y_test": y[ntr:].copy()}
    if r["lengths"]:
        out["L_train"], out["L_test"] = L[:ntr].copy(), L[ntr:].copy()
    rec.update(inputs=("%s: default_rng(%d) X standard normal (n, T=%d, F=%d)%s; label 1 where the strongest "
                       "response of a fixed %d-step motif filter over the valid steps exceeds the training median "
                       "(%.6g); %s" % (DATA_OF[lane], seed, T, F, ", lengths uniform %d..%d, padding noise"
                                       % (max(MOTIF, T // 4), T) if r["lengths"] else "", MOTIF, threshold,
                                       "(F, T) channels-first copy" if r["layout"] == "channels" else "(T, F)")),
               positive_rate_train=float(y[:ntr].mean()),
               shapes={k: list(v.shape) for k, v in out.items()})
    return out


def ours_model(ml, lane, d):
    """The lane's model through the public mojolearn.Sequential layers (uncompiled)."""
    S = ml.Sequential
    T, F = d["length"], d["features"]
    if lane == "seq-cnn1d-fit":
        return (S(input_shape=(F, T)).conv1d(32, 7, padding=3).relu().max_pool1d(2).conv1d(64, 5, padding=2).relu()
                .adaptive_avg_pool1d(1).flatten().linear(1))
    if lane == "seq-resnet1d-fit":
        def body(cin, c):
            return (S().conv1d(c, 5, padding=2, bias=False).batch_norm1d(c).relu()
                    .conv1d(c, 3, padding=1, bias=False).batch_norm1d(c))
        return (S(input_shape=(F, T)).conv1d(32, 7, padding=3, bias=False).batch_norm1d(32).relu()
                .residual_block(body(32, 32)).relu()
                .residual_block(body(32, 64), S().conv1d(64, 1, bias=False).batch_norm1d(64)).relu()
                .adaptive_avg_pool1d(1).flatten().linear(1))
    if lane == "seq-inceptiontime-fit":
        def module(m):
            return (m.parallel(S().conv1d(8, 1, bias=False).conv1d(16, 9, padding=4, bias=False),
                               S().conv1d(8, 1, bias=False).conv1d(16, 5, padding=2, bias=False),
                               S().conv1d(8, 1, bias=False).conv1d(16, 3, padding=1, bias=False),
                               S().max_pool1d(3, 1, padding=1).conv1d(16, 1, bias=False))
                    .batch_norm1d(64).relu())
        return module(module(S(input_shape=(F, T)))).adaptive_avg_pool1d(1).flatten().linear(1)
    if lane in ("seq-gru-lengths-fit", "seq-lstm-lengths-fit"):
        m = S(input_shape=(T, F))
        m = m.gru(64) if lane == "seq-gru-lengths-fit" else m.lstm(64)
        return m.narrow(0, T - 1, 1).flatten().linear(1)
    head = lambda m: m.permute((1, 0)).adaptive_avg_pool1d(1).flatten().linear(1)   # mean over the steps
    if lane == "seq-transformer-fit":
        return head(S(input_shape=(T, F)).linear(64)
                    .residual_block(S().layer_norm().attention(4, rotary=False, causal=False))
                    .residual_block(S().layer_norm().linear(128).gelu().linear(64)).layer_norm())
    if lane == "seq-mamba1-fit":
        return head(S(input_shape=(T, F)).linear(96).softplus().selective_scan(16))
    if lane == "seq-mamba2-fit":
        return head(S(input_shape=(T, F)).linear(321).softplus().ssd_scan(1))
    if lane == "seq-mamba3-fit":
        return head(S(input_shape=(T, F)).linear(102).trapezoid_scan(2, 16))
    raise KeyError(lane)


def torch_model(torch, lane, d, dev):
    """The same model from PyTorch's library modules (and mamba_ssm's scan kernels): an nn.Module whose
    forward(x, lengths=None) returns one logit per row. Raises REFUSED by name when a library op does not
    import on this box (never a harness-written substitute)."""
    nn, Fn = torch.nn, torch.nn.functional
    T, F = d["length"], d["features"]
    kw = dict(device=dev)
    if lane == "seq-cnn1d-fit":
        body = nn.Sequential(nn.Conv1d(F, 32, 7, padding=3, **kw), nn.ReLU(), nn.MaxPool1d(2),
                             nn.Conv1d(32, 64, 5, padding=2, **kw), nn.ReLU(), nn.AdaptiveAvgPool1d(1),
                             nn.Flatten(), nn.Linear(64, 1, **kw))

        class Net(nn.Module):
            def __init__(self):
                super().__init__()
                self.body = body

            def forward(self, x, lengths=None):
                return self.body(x).squeeze(-1)
        return Net()
    if lane == "seq-resnet1d-fit":
        def cbn(cin, c, k, p):
            return [nn.Conv1d(cin, c, k, padding=p, bias=False, **kw), nn.BatchNorm1d(c, eps=1e-5, momentum=0.1, **kw)]

        class Block(nn.Module):
            def __init__(self, cin, c):
                super().__init__()
                self.body = nn.Sequential(*cbn(cin, c, 5, 2), nn.ReLU(), *cbn(c, c, 3, 1))
                self.short = nn.Sequential(*cbn(cin, c, 1, 0)) if cin != c else nn.Identity()

            def forward(self, x):
                return torch.relu(self.body(x) + self.short(x))

        class Net(nn.Module):
            def __init__(self):
                super().__init__()
                self.stem = nn.Sequential(*cbn(F, 32, 7, 3), nn.ReLU())
                self.b1, self.b2 = Block(32, 32), Block(32, 64)
                self.head = nn.Linear(64, 1, **kw)

            def forward(self, x, lengths=None):
                return self.head(self.b2(self.b1(self.stem(x))).mean(-1)).squeeze(-1)
        return Net()
    if lane == "seq-inceptiontime-fit":
        class Inception(nn.Module):
            def __init__(self, cin):
                super().__init__()
                self.branches = nn.ModuleList(
                    [nn.Sequential(nn.Conv1d(cin, 8, 1, bias=False, **kw),
                                   nn.Conv1d(8, 16, k, padding=k // 2, bias=False, **kw)) for k in (9, 5, 3)]
                    + [nn.Sequential(nn.MaxPool1d(3, 1, padding=1), nn.Conv1d(cin, 16, 1, bias=False, **kw))])
                self.bn = nn.BatchNorm1d(64, eps=1e-5, momentum=0.1, **kw)

            def forward(self, x):
                return torch.relu(self.bn(torch.cat([b(x) for b in self.branches], dim=1)))

        class Net(nn.Module):
            def __init__(self):
                super().__init__()
                self.m1, self.m2 = Inception(F), Inception(64)
                self.head = nn.Linear(64, 1, **kw)

            def forward(self, x, lengths=None):
                return self.head(self.m2(self.m1(x)).mean(-1)).squeeze(-1)
        return Net()
    if lane in ("seq-gru-lengths-fit", "seq-lstm-lengths-fit"):
        cell = nn.GRU if lane == "seq-gru-lengths-fit" else nn.LSTM
        pack = nn.utils.rnn.pack_padded_sequence

        class Net(nn.Module):
            def __init__(self):
                super().__init__()
                self.rnn = cell(F, 64, num_layers=1, bias=True, batch_first=True, **kw)
                self.head = nn.Linear(64, 1, **kw)

            def forward(self, x, lengths=None):
                packed = pack(x, lengths, batch_first=True, enforce_sorted=False)
                _, h = self.rnn(packed)
                h = h[0] if isinstance(h, tuple) else h
                return self.head(h[-1]).squeeze(-1)
        return Net()
    if lane == "seq-transformer-fit":
        class Net(nn.Module):
            def __init__(self):
                super().__init__()
                self.inp = nn.Linear(F, 64, **kw)
                self.ln1, self.ln2, self.ln3 = (nn.LayerNorm(64, eps=1e-5, **kw) for _ in range(3))
                self.attn = nn.MultiheadAttention(64, 4, dropout=0.0, bias=False, batch_first=True, **kw)
                self.ff = nn.Sequential(nn.Linear(64, 128, **kw), nn.GELU(approximate="none"), nn.Linear(128, 64, **kw))
                self.head = nn.Linear(64, 1, **kw)

            def forward(self, x, lengths=None):
                h = self.inp(x)
                a = self.ln1(h)
                h = h + self.attn(a, a, a, need_weights=False)[0]
                h = h + self.ff(self.ln2(h))
                return self.head(self.ln3(h).mean(1)).squeeze(-1)
        return Net()
    if lane in ("seq-mamba1-fit", "seq-mamba2-fit"):
        try:
            if lane == "seq-mamba1-fit":
                from mamba_ssm.ops.selective_scan_interface import selective_scan_fn as scan
            else:
                from mamba_ssm.ops.triton.ssd_combined import mamba_chunk_scan_combined as scan
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError("REFUSED: %s: mamba_ssm's scan kernel does not import (%r); a harness-written "
                               "scan is not an opponent" % (lane, exc))
        import math

        class Net(nn.Module):
            def __init__(self):
                super().__init__()
                if lane == "seq-mamba1-fit":
                    self.dim, self.n = 32, 16
                    self.proj = nn.Linear(F, 2 * self.dim + 2 * self.n, **kw)
                    a_log = torch.log(torch.arange(1, self.n + 1, dtype=torch.float32, device=dev)).repeat(self.dim, 1)
                    self.D = nn.Parameter(torch.ones(self.dim, device=dev))
                else:
                    self.dim, self.n = 64, 128
                    self.proj = nn.Linear(F, 65 + 256, **kw)
                    a_log = torch.full((1,), math.log(1.0), device=dev)
                    self.D = nn.Parameter(torch.ones(1, device=dev))
                self.A_log = nn.Parameter(a_log)
                self.head = nn.Linear(self.dim, 1, **kw)

            def forward(self, x, lengths=None):
                z = Fn.softplus(self.proj(x))
                b, t = z.shape[0], z.shape[1]
                A = -torch.exp(self.A_log.float())
                if lane == "seq-mamba1-fit":
                    u, delta, B, C = torch.split(z, [self.dim, self.dim, self.n, self.n], dim=-1)
                    tr = lambda v: v.transpose(1, 2).contiguous()
                    y = scan(tr(u), tr(delta), A, tr(B), tr(C), D=self.D.float(), delta_softplus=False)
                    pooled = y.mean(-1)
                else:
                    xs, B, C, dt = torch.split(z, [self.dim, self.n, self.n, 1], dim=-1)
                    y = scan(xs.reshape(b, t, 1, self.dim), dt.reshape(b, t, 1), A, B.reshape(b, t, 1, self.n),
                             C.reshape(b, t, 1, self.n), chunk_size=256, D=self.D)
                    pooled = y.reshape(b, t, self.dim).mean(1)
                return self.head(pooled).squeeze(-1)
        return Net()
    raise RuntimeError("REFUSED: %s: %s" % (lane, LANES[lane].get("no_opponent", "no torch model")))


