"""Module and CPython admission happens in the doors, once per public call.

    python3 tools/check_admitted_call.py              # whole runtime tree
    python3 tools/check_admitted_call.py FILE...      # these files only
    python3 tools/check_admitted_call.py --baseline   # print current counts (to shrink DEBT)

THE RULE (plan docs/plans/NATIVE_ENTRY_POINTS_AFTER_0866.md, workstream E).
A public call admits its modules, binding, model fields and inputs once, in
its door, into one `AdmittedCall` (bindings/admitted_call.mojo) passed by
reference to every helper. A helper that calls `native_loaded_module(`,
`Python.import_module(` or `.cpython()` itself re-admits what the door
already holds. Those three forms are therefore allowed only in:

- DOORS: the module loader, the record and table constructors, and the
  public doors that build the AdmittedCall (listed below, unlimited);
- DEBT: every other runtime file that used them when this guard landed,
  each with the count it had then. A file's count may go down, never up,
  and a file not listed may not use them at all. When a lane removes uses,
  it lowers the file's number here in the same commit (`--baseline` prints
  the current counts); a file whose count reaches zero is deleted from DEBT.

The scan covers the runtime Mojo trees (bindings/, providers/, core/).
Comment lines (first non-blank character `#`) are not counted. Tests,
benches, experiments and training scripts are out of scope.

Exit status: 0 clean, 1 a file exceeds its allowance (each one printed as
`ADMITTED-CALL <file> <form> <count> > <allowed>`).
"""
