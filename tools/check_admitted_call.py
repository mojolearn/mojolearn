def count_forms(text):
    """{form: occurrences} over the non-comment lines of one source."""
    counts = {}
    for line in text.splitlines():
        if line.lstrip().startswith("#"):
            continue
        for form, pattern in FORMS.items():
            hits = len(pattern.findall(line))
            if hits:
                counts[form] = counts.get(form, 0) + hits
    return counts


def runtime_files(repo=REPO):
    for root in ROOTS:
        base = repo / root
        if base.is_dir():
            yield from sorted(base.rglob("*.mojo"))


def violations(sources, doors=DOORS, debt=None):
    """`sources`: {relative path: text}. Returns [(path, form, count, allowed)]."""
    debt = DEBT if debt is None else debt
    found = []
    for path in sorted(sources):
        if path in doors:
            continue
        allowed = debt.get(path, {})
        for form, count in sorted(count_forms(sources[path]).items()):
            limit = allowed.get(form, 0)
            if count > limit:
                found.append((path, form, count, limit))
    return found


def _read(paths, repo=REPO):
    sources = {}
    for path in paths:
        rel = path.resolve().relative_to(repo).as_posix()
        sources[rel] = path.read_text(encoding="utf-8", errors="replace")
    return sources


def baseline(sources, doors=DOORS):
    rows = {}
    for path in sorted(sources):
        if path in doors:
            continue
        counts = count_forms(sources[path])
        if counts:
            rows[path] = dict(sorted(counts.items()))
    return rows


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="*", type=Path)
    parser.add_argument("--baseline", action="store_true", help="print the current DEBT table and exit 0")
    args = parser.parse_args(argv)
    paths = [p if p.is_absolute() else (Path.cwd() / p) for p in args.files] or list(runtime_files())
    sources = _read(paths)
    if args.baseline:
        for path, counts in baseline(sources).items():
            print(f"    {path!r}: {counts!r},")
        return 0
    found = violations(sources)
    for path, form, count, limit in found:
        print(f"ADMITTED-CALL {path} {form} {count} > {limit}")
    print(f"check_admitted_call: {len(sources)} files, {len(found)} over allowance")
    return 1 if found else 0


