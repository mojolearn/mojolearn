#!/usr/bin/env python3
"""Merged bindings: one native file per installed directory set.

Every binding `bindings/<name>.mojo` defines its module body as
`def build_<name>() -> PythonObject` (no @export). Two kinds of root file export
the CPython module init that calls it:

  bindings/entry/entry_<name>.mojo   one PyInit_<name>; what the per-binding
                                     build script compiles (development, A/Bs,
                                     bisecting). Written by `entries`.
  a merged root                      one PyInit per member of a group in
                                     bindings/merged_groups.json; compiled ONCE
                                     by bindings/merged_build.sh into
                                     <dir>/<stem>.so, so code the members share
                                     (sequence ops, linalg, common kernels, the
                                     stdlib) is compiled and embedded once.
                                     Written by `root`, at build time.

The merged file also exports PyInit_<stem>, a module whose `merged_members()`
names its members, so a tool that loads every .so by its stem still loads it.
`index` writes <dir>/_mojolearn_merged.json (stem.so -> members), which
python/mojolearn/_merged.py reads to load a member from the merged file when
the member's own .so is absent.

This is build tooling: it never runs in the library.

  python3 tools/merged_bindings.py entries [--check]
  python3 tools/merged_bindings.py members --dir fast|identical|host [--platform P] [--byte-lm 0|1]
  python3 tools/merged_bindings.py plan --dir D [--platform P] [--byte-lm 0|1]
        one line per merged file: <stem> <flags-class> <member,member,...>
  python3 tools/merged_bindings.py root --stem S --members a,b,c --out FILE
  python3 tools/merged_bindings.py index --outdir DIR --stem S --members a,b,c
  python3 tools/merged_bindings.py check --dir D --expect "a b c" [--platform P] [--byte-lm 0|1]
        exit 1 unless the manifest's members for D equal the packer's list
  python3 tools/merged_bindings.py owner --outdir DIR --name N
        print the merged file in DIR that holds N (from its index), or nothing
"""
import argparse
import json
import os
import pathlib
import platform as _platform
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = REPO / "bindings" / "merged_groups.json"
ENTRY_DIR = REPO / "bindings" / "entry"
INDEX_FORMAT = 1


def manifest():
    return json.loads(MANIFEST.read_text())


def default_platform():
    return "darwin" if _platform.system() == "Darwin" else "linux"


def members(dir_name, plat, byte_lm):
    """{stem: [members]} for one directory set on one platform."""
    m = manifest()
    d = m["dirs"][dir_name]
    out = {}
    for stem, names in d["groups"].items():
        names = list(names)
        if byte_lm:
            for opt, plats in d.get("optional", {}).items():
                if plat in plats and opt not in names:
                    names.append(opt)
        out[stem] = names
    return out


def plan(dir_name, plat, byte_lm):
    """[(stem, flags_class, [members])]: the files one build of `dir_name`
    writes. On macOS a group splits by flags class so each member keeps the
    exact compile flags its own build script passes."""
    m = manifest()
    metal1 = set(m.get("darwin_metal1", []))
    suffix = m.get("darwin_metal1_suffix", "_m1")
    rows = []
    for stem, names in members(dir_name, plat, byte_lm).items():
        if dir_name == "host":
            rows.append((stem, "host", names))
            continue
        if plat == "darwin":
            base = [n for n in names if n not in metal1]
            one = [n for n in names if n in metal1]
            if base:
                rows.append((stem, "default", base))
            if one:
                rows.append((stem + suffix, "metal1", one))
        else:
            rows.append((stem, "default", names))
    return rows


def binding_names():
    """Every binding source with a module body builder, sorted."""
    out = []
    for f in sorted((REPO / "bindings").glob("_mojolearn*.mojo")):
        if f"def build_{f.stem}() -> PythonObject:" in f.read_text(errors="replace"):
            out.append(f.stem)
    return out


ENTRY = '''\
# GENERATED by tools/merged_bindings.py entries; do not edit.
# The per-binding entry for {name}: the CPython module init the per-binding
# build script compiles. The module body is build_{name}() in
# bindings/{name}.mojo; bindings/merged_build.sh exports the same init from one
# shared file per directory set (bindings/merged_groups.json).
from std.python import PythonObject
from {name} import build_{name}


@export
def PyInit_{name}() abi("C") -> PythonObject:
    return build_{name}()
'''


def entry_text(name):
    return ENTRY.format(name=name)


def cmd_entries(args):
    want = {f"entry_{n}.mojo": entry_text(n) for n in binding_names()}
    have = {p.name: p.read_text() for p in ENTRY_DIR.glob("entry_*.mojo")} if ENTRY_DIR.is_dir() else {}
    stale = sorted(k for k in want if have.get(k) != want[k])
    extra = sorted(k for k in have if k not in want)
    if args.check:
        for k in stale:
            print(f"stale or missing: bindings/entry/{k}")
        for k in extra:
            print(f"no binding for: bindings/entry/{k}")
        return 1 if stale or extra else 0
    ENTRY_DIR.mkdir(exist_ok=True)
    for k in stale:
        (ENTRY_DIR / k).write_text(want[k])
    for k in extra:
        (ENTRY_DIR / k).unlink()
    print(f"bindings/entry: {len(want)} entries ({len(stale)} written, {len(extra)} removed)")
    return 0


ROOT_HEAD = '''\
# GENERATED by tools/merged_bindings.py root for {stem}.so; do not edit.
# One CPython module init per member; each calls the module body its binding
# file defines (build_<name>), so every member keeps its module name and the
# code they share is compiled once. PyInit_{stem} names the members.
from std.os import abort
from std.python import PythonObject
from std.python.bindings import PythonModuleBuilder
'''

ROOT_MEMBER = '''

@export
def PyInit_{name}() abi("C") -> PythonObject:
    return build_{name}()
'''

ROOT_TAIL = '''

def merged_members_binding() raises -> PythonObject:
    return PythonObject(String("{names}"))


@export
def PyInit_{stem}() abi("C") -> PythonObject:
    try:
        var m = PythonModuleBuilder("{stem}")
        m.def_function[merged_members_binding]("merged_members")
        return m.finalize()
    except e:
        abort(String(e))
'''


def root_text(stem, names):
    known = set(binding_names())
    missing = [n for n in names if n not in known]
    if missing:
        raise SystemExit(f"merged_bindings: no module body builder for {', '.join(missing)}")
    if len(set(names)) != len(names) or stem in names:
        raise SystemExit("merged_bindings: duplicate member or member named like the merged file")
    s = [ROOT_HEAD.format(stem=stem)]
    s += [f"from {n} import build_{n}\n" for n in names]
    s += [ROOT_MEMBER.format(name=n) for n in names]
    s.append(ROOT_TAIL.format(stem=stem, names=",".join(names)))
    return "".join(s)


def cmd_root(args):
    names = [n for n in args.members.split(",") if n]
    pathlib.Path(args.out).write_text(root_text(args.stem, names))
    return 0


def index_path(outdir):
    return pathlib.Path(outdir) / manifest()["index_file"]


def read_index(outdir):
    p = index_path(outdir)
    if not p.is_file():
        return {"format": INDEX_FORMAT, "files": {}}
    return json.loads(p.read_text())


def cmd_index(args):
    names = [n for n in args.members.split(",") if n]
    idx = read_index(args.outdir)
    files = idx.setdefault("files", {})
    fname = args.stem + ".so"
    # a member lives in exactly one merged file per directory
    for other, mem in list(files.items()):
        if other != fname:
            files[other] = [n for n in mem if n not in names]
            if not files[other]:
                del files[other]
    files[fname] = names
    idx["format"] = INDEX_FORMAT
    p = index_path(args.outdir)
    tmp = p.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(idx, indent=1, sort_keys=True) + "\n")
    os.replace(tmp, p)
    print(f"indexed {p}: {fname} holds {len(names)} member(s)")
    return 0


def cmd_owner(args):
    for fname, mem in read_index(args.outdir).get("files", {}).items():
        if args.name in mem:
            print(os.path.join(args.outdir, fname))
            return 0
    return 0


def cmd_members(args):
    names = []
    for _stem, _cls, mem in plan(args.dir, args.platform, args.byte_lm):
        names += mem
    print(" ".join(names))
    return 0


def cmd_plan(args):
    for stem, cls, mem in plan(args.dir, args.platform, args.byte_lm):
        print(stem, cls, ",".join(mem))
    return 0


def cmd_check(args):
    got = []
    for _stem, _cls, mem in plan(args.dir, args.platform, args.byte_lm):
        got += mem
    want = args.expect.split()
    if sorted(got) != sorted(want):
        print(f"merged_bindings: bindings/merged_groups.json dir {args.dir} ({args.platform}, "
              f"byte LM {int(args.byte_lm)}) does not match the packer's list", file=sys.stderr)
        print(f"  only in the manifest: {' '.join(sorted(set(got) - set(want))) or '-'}", file=sys.stderr)
        print(f"  only in the packer:   {' '.join(sorted(set(want) - set(got))) or '-'}", file=sys.stderr)
        return 1
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(p):
        p.add_argument("--dir", required=True, choices=("fast", "identical", "host"))
        p.add_argument("--platform", default=default_platform(), choices=("darwin", "linux"))
        p.add_argument("--byte-lm", type=lambda s: s == "1",
                       default=os.environ.get("MOJOLEARN_PACKAGE_BYTE_LM", "0") == "1")

    p = sub.add_parser("entries"); p.add_argument("--check", action="store_true"); p.set_defaults(fn=cmd_entries)
    p = sub.add_parser("members"); common(p); p.set_defaults(fn=cmd_members)
    p = sub.add_parser("plan"); common(p); p.set_defaults(fn=cmd_plan)
    p = sub.add_parser("check"); common(p); p.add_argument("--expect", required=True); p.set_defaults(fn=cmd_check)
    p = sub.add_parser("root")
    p.add_argument("--stem", required=True); p.add_argument("--members", required=True)
    p.add_argument("--out", required=True); p.set_defaults(fn=cmd_root)
    p = sub.add_parser("index")
    p.add_argument("--outdir", required=True); p.add_argument("--stem", required=True)
    p.add_argument("--members", required=True); p.set_defaults(fn=cmd_index)
    p = sub.add_parser("owner")
    p.add_argument("--outdir", required=True); p.add_argument("--name", required=True); p.set_defaults(fn=cmd_owner)
    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
