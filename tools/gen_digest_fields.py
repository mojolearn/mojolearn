#!/usr/bin/env python3
"""Write docs/api/DIGEST_FIELDS.md: what `model.digest_` hashes, per public class.

Read from the sources the compiled walk reads (bindings/fitted_digest_door.mojo),
in an installed Mojolearn:

- `mojolearn._digest_fields`: REFUSED (no digest yet, with the reason), EXTRA
  (private fitted fields added) and SKIP (public fields left out);
- the save schemas the classes registered (`_native_archive_bridge`, the
  context's `archive_save_schemas`): the members `save` writes;
- the rule for every other class: its public fitted attributes.

It imports the package and builds no estimator, fits nothing and calls no
compiled operation: the table is class metadata only. One class is one
independent unit; the units are a few hundred dictionary reads, so they run in
one pass (nothing to split across cores).

    python tools/gen_digest_fields.py            # writes docs/api/DIGEST_FIELDS.md
    python tools/gen_digest_fields.py --check    # exit 1 when the file is stale
"""
import argparse
import sys
from pathlib import Path

#: step kind -> the positions of the member names it writes
MEMBER_AT = {
    "format": (1,), "estimator": (1,), "mode": (1,), "str": (1,), "lower": (1,), "init_name": (1,),
    "array": (1,), "flat": (1,), "head": (1,), "reshape": (1,), "i8": (1,), "i4": (1,), "f8": (1,), "f4": (1,),
    "classes": (1,), "utf8": (1,), "class_table": (1,), "stack": (1,), "rows": (1,), "device_array": (1,),
    "concat": (1,), "kernel": (4, 5, 6, 7),
}
#: step kinds that only check or derive, and write no member
NO_MEMBER = {"need", "need_set", "need_true", "need_str", "refuse_set", "refuse_in", "need_eq", "need_in",
             "choice", "check_array", "need_either"}
#: step kinds whose last item is a nested step list (written under a condition)
NESTED = {"when", "when_set", "unless", "when_in", "when_none"}


def members(steps, conditional=False):
    """(member name, conditional) for every member a schema writes, in schema order."""
    found = []
    for step in steps:
        kind = step[0]
        if kind in NESTED:
            found.extend(members(step[-1], True))
        elif kind in MEMBER_AT:
            found.extend((str(step[i]), conditional) for i in MEMBER_AT[kind] if i < len(step))
        elif kind not in NO_MEMBER:
            found.append((f"(step {kind})", conditional))
    return found


def lookup(cls, table):
    """The table entry of `cls` or its nearest ancestor, as the compiled walk looks it up."""
    for base in cls.__mro__:
        if base in table:
            return table[base]
    return None


def rows(ml):
    from mojolearn import _digest_fields as fields, _native_archive_bridge as bridge
    from mojolearn._mode import CheckMixin
    _, context = bridge.connect()
    schemas = context.get("archive_save_schemas", {})
    out = []
    for name in sorted(n for n in ml.__all__ if n[:1].isupper()):
        cls = getattr(ml, name, None)
        if not isinstance(cls, type) or not callable(getattr(cls, "fit", None)):
            continue
        if not issubclass(cls, CheckMixin):
            out.append((name, "no `digest_`", "the class is not on the shared estimator base"))
            continue
        reason = lookup(cls, fields.REFUSED)
        if reason is not None:
            out.append((name, "not yet", reason))
            continue
        steps = lookup(cls, schemas)
        if steps is not None and not isinstance(steps, str):
            listed = ", ".join(f"`{m}`" + (" (when present)" if cond else "") for m, cond in members(steps))
            out.append((name, "save schema", listed))
            continue
        extra = lookup(cls, fields.EXTRA) or ()
        skip = lookup(cls, fields.SKIP) or ()
        text = "every public fitted attribute (name ends in `_`, value not None)"
        if skip:
            text += "; without " + ", ".join(f"`{n}`" for n in skip)
        if extra:
            text += "; plus " + ", ".join(f"`{n}`" for n in extra)
        out.append((name, "public fitted attributes", text))
    return out


def render(table):
    lines = [
        "# What `digest_` hashes",
        "",
        "Generated by `tools/gen_digest_fields.py` from the tables and save schemas the compiled digest walk reads. Do not edit.",
        "",
        "Every digest starts with the format word `mojolearn.digest.v1` and the class name. Then each field below, in",
        "name order, as its name, dtype, shape and bytes in C order. A list, tuple or dictionary field is entered item by",
        "item; a member estimator contributes its own digest.",
        "",
        "| Class | Source | Fields |",
        "|---|---|---|",
    ]
    lines.extend(f"| `{name}` | {source} | {text} |" for name, source, text in table)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "docs/api/DIGEST_FIELDS.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    import mojolearn as ml
    text = render(rows(ml))
    if args.check:
        current = args.out.read_text() if args.out.is_file() else ""
        if current != text:
            print(f"STALE: {args.out}; run tools/gen_digest_fields.py", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
