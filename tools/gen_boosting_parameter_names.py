"""Write docs/api/BOOSTING_PARAMETER_NAMES.md from the one name table,
python/mojolearn/_boosting_param_names.py.

The table module imports nothing from the package, so it is loaded from its
file and the compiled library is never imported. `--check` exits 1 when the
page differs from what the table generates.
"""
import argparse
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TABLE = ROOT / "python" / "mojolearn" / "_boosting_param_names.py"
PAGE = ROOT / "docs" / "api" / "BOOSTING_PARAMETER_NAMES.md"


def _table():
    spec = importlib.util.spec_from_file_location("_boosting_param_names", TABLE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render():
    t = _table()
    rows = t.BOOSTING_PARAMETER_NAMES
    out = [
        "# CatBoost, XGBoost and LightGBM parameter names",
        "",
        "<!-- Generated by tools/gen_boosting_parameter_names.py from",
        "python/mojolearn/_boosting_param_names.py; do not edit by hand. -->",
        "",
        "`GradientBoosting`, `GradientBoostingClassifier` and `GradientBoostingRegressor` accept the",
        "parameter names of CatBoost, XGBoost and LightGBM wherever the name means the same thing as one",
        "of their own parameters. The value is stored under Mojolearn's name, and `get_params` reports",
        "that name, so a model built with `iterations=500` reports `n_estimators=500`.",
        "",
        "- A name is accepted in the constructor and in `set_params`, and nowhere else.",
        "- Giving two names for one parameter with different values raises `ValueError`.",
        "- A name that means something different in another library raises `ValueError` and names the",
        "  parameter to use instead. It is never mapped.",
        "- A name is accepted only by a class that has the parameter it stands for (the loss and",
        "  categorical names only by `GradientBoosting`).",
        "",
        "## Accepted names",
        "",
        "| Name | Mojolearn parameter | Used by |",
        "| --- | --- | --- |",
    ]
    for name, canonical, libraries, same, _note in sorted(
            (r for r in rows if r[3]), key=lambda r: (r[1], r[0])):
        out.append(f"| `{name}` | `{canonical}` | {', '.join(libraries)} |")
    out += [
        "",
        "## Refused names",
        "",
        "| Name | Use instead | Why |",
        "| --- | --- | --- |",
    ]
    for name, canonical, libraries, same, note in sorted(
            (r for r in rows if not r[3]), key=lambda r: (r[1], r[0])):
        out.append(f"| `{name}` ({', '.join(libraries)}) | `{canonical}` | {note} |")
    out += [
        "",
        "## Same name, other values",
        "",
        "These are Mojolearn's own parameter names, so they are taken as given; values from another",
        "library's vocabulary raise `ValueError`.",
        "",
        "| Name | Other library | Values |",
        "| --- | --- | --- |",
    ]
    for name, libraries, note in t.SAME_NAME_OTHER_VALUES:
        out.append(f"| `{name}` | {', '.join(libraries)} | {note} |")
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the page is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = PAGE.read_text() if PAGE.exists() else ""
        if current != text:
            print(f"{PAGE.relative_to(ROOT)} is stale: run tools/gen_boosting_parameter_names.py")
            return 1
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
