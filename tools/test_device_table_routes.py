"""`python/mojolearn/_device_table.py` carries the host surface manifest's one
answer it needs (`CPU_TRAINING_ROUTES`, generated by
`tools/device_class_table.py --write-routes`) instead of importing the manifest
at every `import mojolearn`. Source checks only: nothing is built or imported
from the package."""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import device_class_table  # noqa: E402

TABLE = device_class_table.DEVICE_TABLE


def _source():
    return open(TABLE, encoding="utf-8").read()


def test_the_generated_routes_are_the_manifest_answer():
    source = _source()
    assert source.count(device_class_table.BEGIN) == 1 and source.count(device_class_table.END) == 1
    block = source.split(device_class_table.BEGIN, 1)[1].split(device_class_table.END, 1)[0]
    assert block == device_class_table.routes_block(), \
        "stale: run `python3 tools/device_class_table.py --write-routes`"
    namespace = {}
    exec(block, namespace)
    expected = set(device_class_table._host_surface().cpu_training_routes())
    assert expected and namespace["CPU_TRAINING_ROUTES"] == expected


def test_the_device_table_imports_no_manifest():
    tree = ast.parse(_source())
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            imported.update([node.module or ""] + [alias.name for alias in node.names])
        elif isinstance(node, ast.Import):
            imported.update(alias.name for alias in node.names)
    assert not {name for name in imported if "host_surface" in name}, imported
    assert "host_surface." not in "".join(ast.unparse(n) for n in tree.body if not isinstance(n, ast.Expr))


def test_answer_reads_the_generated_routes():
    tree = ast.parse(_source())
    answer = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "answer")
    assert "binding not in CPU_TRAINING_ROUTES" in ast.unparse(answer)


if __name__ == "__main__":
    for name, fn in sorted(globals().items()):
        if name.startswith("test_") and callable(fn):
            fn()
    print("ok")
