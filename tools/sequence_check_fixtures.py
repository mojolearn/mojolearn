"""Write the stored inputs of the sequence checks that depend on NumPy's
PCG64 stream (lane tmig-sequence-2, 2026-11-14).

    python tools/sequence_check_fixtures.py

checks/fixtures/sequence/garch_sim_n1500_seed0.f32: the GARCH(1, 1) series
of the former python/mojolearn/tests/test_x_sequence_garch.py `_sim()`
(n = 1500, default_rng(0), omega 0.05, alpha 0.1, beta 0.85), float32
little-endian, read by checks/native_tests/sequence_garch.mojo. The
recovery tolerance of that check was set on this sample, so the sample is
stored, not regenerated by another generator.

Testing tool only; nothing in the package imports it.
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "checks" / "fixtures" / "sequence"


def garch_sim(n=1500, seed=0):
    rng = np.random.default_rng(seed)
    r = np.zeros(n)
    s2 = 1.0
    for t in range(n):  # the original recursion, one draw per step in order
        r[t] = np.sqrt(s2) * rng.standard_normal()
        s2 = 0.05 + 0.1 * r[t] ** 2 + 0.85 * s2
    return r.astype("<f4")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "garch_sim_n1500_seed0.f32").write_bytes(garch_sim().tobytes())


if __name__ == "__main__":
    main()
